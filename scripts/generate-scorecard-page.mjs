#!/usr/bin/env node

import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';

const rootArgument = process.argv.slice(2).find((argument) => !argument.startsWith('--'));
const root = resolve(rootArgument ?? '.');
const check = process.argv.includes('--check');
const output = join(root, 'docs/reference/scorecard.md');
const recordDirectory = 'record/proofs/compliance/scorecards';
const repositoryUrl = 'https://github.com/aarusso-nyx/devai';
const substrates = [
  ['F1', 'Specification'],
  ['F2', 'Plant'],
  ['F3', 'Observation'],
  ['F4', 'Inventory'],
  ['F5', 'Harness'],
];
const properties = [
  ['T1', 'Coverage'],
  ['T2', 'Depth'],
  ['T3', 'Coherence'],
  ['T4', 'Alignment'],
  ['T5', 'Idiomaticity'],
  ['T6', 'Security and Privacy'],
  ['T7', 'Performance and Efficiency'],
  ['T8', 'Robustness'],
  ['T9', 'Discipline'],
];
const verdicts = ['PASS', 'REVIEW', 'FAIL', 'UNKNOWN', 'N/A'];

function newestScorecardId() {
  const ids = readdirSync(join(root, recordDirectory))
    .map((name) => /^(SC-[0-9A-Z-]+)\.json$/u.exec(name)?.[1])
    .filter((id) => id !== undefined)
    .sort();
  const id = ids.at(-1);
  if (id === undefined) throw new Error(`SCORECARD_PAGE_RECORD_MISSING:${recordDirectory}`);
  return id;
}

function readJson(path) {
  return JSON.parse(readFileSync(join(root, path), 'utf8'));
}

function text(value) {
  return String(value).replaceAll('|', '\\|').replaceAll(/\s+/gu, ' ').trim();
}

function table(header, rows) {
  const all = [header, ...rows];
  const widths = header.map((_, column) =>
    Math.max(3, ...all.map((row) => [...row[column]].length)),
  );
  const line = (row) =>
    `| ${row.map((cell, column) => cell + ' '.repeat(widths[column] - [...cell].length)).join(' | ')} |`;
  return [
    line(header),
    `| ${widths.map((width) => '-'.repeat(width)).join(' | ')} |`,
    ...rows.map(line),
  ].join('\n');
}

function marked(cell) {
  const marks = [];
  if (cell.deterministic === false) marks.push('nd');
  if (cell.notes !== undefined) marks.push('note');
  return marks.length === 0 ? cell.verdict : `${cell.verdict} (${marks.join(', ')})`;
}

function firstParagraph(narrative) {
  const paragraph =
    String(narrative ?? '')
      .split('\n')[0]
      ?.trim() ?? '';
  const sentences = paragraph.split(/(?<=[.:])\s+/u);
  if (sentences.length > 1 && sentences.at(-1)?.endsWith(':')) sentences.pop();
  return sentences.join(' ');
}

const id = newestScorecardId();
const scorecard = readJson(`${recordDirectory}/${id}.json`);
const assessment = readJson(`${recordDirectory}/${id}.assessment.json`);
if (scorecard.id !== id || assessment.scorecard_id !== id) {
  throw new Error(`SCORECARD_PAGE_RECORD_MISMATCH:${id}`);
}
const cells = new Map(scorecard.cells.map((cell) => [`${cell.substrate}${cell.property}`, cell]));
const counts = verdicts.map(
  (verdict) =>
    `${verdict} ${String(scorecard.cells.filter((cell) => cell.verdict === verdict).length)}`,
);
const grid = table(
  ['Substrate', ...properties.map(([key, title]) => `${key} ${title}`)],
  substrates.map(([substrate, title]) => [
    `${substrate} ${title}`,
    ...properties.map(([property]) => {
      const cell = cells.get(`${substrate}${property}`);
      return cell === undefined ? 'missing' : marked(cell);
    }),
  ]),
);
const notPassing = scorecard.cells
  .filter((cell) => cell.verdict !== 'PASS')
  .map((cell) => {
    const readings = (cell.sensor_readings ?? []).map((reading) => `\`${reading}\``).join(', ');
    const parts = [`- ${cell.substrate} × ${cell.property}: ${cell.verdict}`];
    parts.push(readings === '' ? 'no sensor readings' : `readings ${readings}`);
    if (cell.notes !== undefined) parts.push(`note: ${text(cell.notes)}`);
    return parts.join('; ');
  });
const recordBase = `../../${recordDirectory}/${id}`;
const head = String(scorecard.integration_head);

const content = `---
title: Self-scorecard
---

<!-- @generated by scripts/generate-scorecard-page.mjs; do not edit -->

# Self-scorecard

This page renders the newest self-scorecard recorded under \`${recordDirectory}/\`. The record
files linked below are authoritative; this page is regenerated from them.

- Scorecard: \`${id}\`
- Integration head: [\`${head.slice(0, 8)}\`](${repositoryUrl}/commit/${head})
- Generated at: ${scorecard.generated_at}
- Overall verdict: **${scorecard.overall.verdict}**
- Cells: ${counts.join(', ')}

## Aspect grid

A cell marked \`nd\` was computed from a non-deterministic reading; a cell marked \`note\` carries a
note, listed below when the cell is not at PASS.

${grid}

## Cells not at PASS

${notPassing.join('\n')}

## Assessment

${firstParagraph(assessment.narrative)}

## Record

- [Scorecard](${recordBase}.json)
- [Assessment](${recordBase}.assessment.json)
- [Backlog](${recordBase}.backlog.json)
`;

if (check) {
  if (!existsSync(output) || readFileSync(output, 'utf8') !== content) {
    throw new Error(`SCORECARD_PAGE_DRIFT:${relative(root, output)}`);
  }
  process.stdout.write(`scorecard page: PASS (${id})\n`);
} else {
  writeFileSync(output, content);
  process.stdout.write(`scorecard page: generated ${id}\n`);
}
